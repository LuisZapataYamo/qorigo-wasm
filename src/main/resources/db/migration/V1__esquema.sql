CREATE TABLE persona (
    id_persona         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres            VARCHAR(120) NOT NULL,
    apellidos          VARCHAR(120) NOT NULL,
    nombre_normalizado VARCHAR(250) NOT NULL,
    documento          VARCHAR(30),
    telefono           VARCHAR(30),
    email              VARCHAR(150),
    direccion          VARCHAR(250),
    activo             BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_persona_documento UNIQUE (documento)
);
CREATE INDEX ix_persona_nombre_normalizado ON persona (nombre_normalizado);

CREATE TABLE usuario (
    id_usuario    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona    BIGINT NOT NULL,
    email_login   VARCHAR(150) NOT NULL,
    password_hash VARCHAR(120) NOT NULL,
    rol           VARCHAR(10) NOT NULL,
    activo        BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_usuario_email UNIQUE (email_login),
    CONSTRAINT uq_usuario_persona UNIQUE (id_persona),
    CONSTRAINT fk_usuario_persona FOREIGN KEY (id_persona) REFERENCES persona (id_persona),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('ADMIN', 'MEMBER'))
);

CREATE TABLE recuperacion_password (
    id_recuperacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario      BIGINT NOT NULL,
    token_hash      CHAR(64) NOT NULL,
    expira_en       TIMESTAMP WITH TIME ZONE NOT NULL,
    usado           BOOLEAN NOT NULL DEFAULT FALSE,
    creado_en       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_recuperacion_token UNIQUE (token_hash),
    CONSTRAINT fk_recuperacion_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
);

CREATE TABLE moneda (
    codigo    CHAR(3) PRIMARY KEY,
    nombre    VARCHAR(60) NOT NULL,
    decimales SMALLINT NOT NULL DEFAULT 2,
    CONSTRAINT ck_moneda_decimales CHECK (decimales BETWEEN 0 AND 4)
);

CREATE TABLE plataforma (
    id_plataforma BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(120) NOT NULL,
    descripcion   VARCHAR(250),
    activo        BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_plataforma_nombre UNIQUE (nombre)
);

CREATE TABLE suscripcion (
    id_suscripcion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_plataforma  BIGINT NOT NULL,
    moneda         CHAR(3) NOT NULL,
    nombre         VARCHAR(150) NOT NULL,
    costo          NUMERIC(12,2) NOT NULL,
    periodicidad   VARCHAR(20) NOT NULL DEFAULT 'MENSUAL',
    capacidad      SMALLINT NOT NULL,
    dia_cobro      SMALLINT NOT NULL,
    fecha_inicio   DATE NOT NULL,
    estado         VARCHAR(20) NOT NULL,
    creado_en      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_suscripcion_plataforma FOREIGN KEY (id_plataforma) REFERENCES plataforma (id_plataforma),
    CONSTRAINT fk_suscripcion_moneda FOREIGN KEY (moneda) REFERENCES moneda (codigo),
    CONSTRAINT ck_suscripcion_costo CHECK (costo > 0),
    CONSTRAINT ck_suscripcion_capacidad CHECK (capacidad >= 1),
    CONSTRAINT ck_suscripcion_dia_cobro CHECK (dia_cobro BETWEEN 1 AND 31),
    CONSTRAINT ck_suscripcion_estado CHECK (estado IN ('ACTIVA', 'SUSPENDIDA', 'CANCELADA'))
);

CREATE TABLE costo_suscripcion_periodo (
    id_costo       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_suscripcion BIGINT NOT NULL,
    periodo        DATE NOT NULL,
    monto          NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_costo_suscripcion FOREIGN KEY (id_suscripcion) REFERENCES suscripcion (id_suscripcion),
    CONSTRAINT uq_costo_periodo UNIQUE (id_suscripcion, periodo),
    CONSTRAINT ck_costo_monto CHECK (monto >= 0)
);

CREATE TABLE miembro_suscripcion (
    id_miembro     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_suscripcion BIGINT NOT NULL,
    id_persona     BIGINT NOT NULL,
    monto_acordado NUMERIC(12,2) NOT NULL,
    es_plaza_propia BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_inicio   DATE NOT NULL,
    fecha_fin      DATE,
    estado         VARCHAR(10) NOT NULL,
    creado_en      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_miembro_suscripcion FOREIGN KEY (id_suscripcion) REFERENCES suscripcion (id_suscripcion),
    CONSTRAINT fk_miembro_persona FOREIGN KEY (id_persona) REFERENCES persona (id_persona),
    CONSTRAINT ck_miembro_monto CHECK (monto_acordado >= 0),
    CONSTRAINT ck_miembro_estado CHECK (estado IN ('ACTIVO', 'INACTIVO')),
    CONSTRAINT ck_miembro_plaza_propia CHECK (es_plaza_propia = FALSE OR monto_acordado = 0)
);
CREATE INDEX ix_miembro_suscripcion ON miembro_suscripcion (id_suscripcion);
CREATE INDEX ix_miembro_persona ON miembro_suscripcion (id_persona);
CREATE INDEX ix_miembro_activo ON miembro_suscripcion (id_suscripcion, id_persona, estado);

CREATE TABLE cargo_suscripcion (
    id_cargo          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_miembro        BIGINT NOT NULL,
    periodo           DATE NOT NULL,
    monto             NUMERIC(12,2) NOT NULL,
    fecha_vencimiento DATE NOT NULL,
    estado            VARCHAR(10) NOT NULL,
    CONSTRAINT fk_cargo_miembro FOREIGN KEY (id_miembro) REFERENCES miembro_suscripcion (id_miembro),
    CONSTRAINT uq_cargo_miembro_periodo UNIQUE (id_miembro, periodo),
    CONSTRAINT ck_cargo_monto CHECK (monto >= 0),
    CONSTRAINT ck_cargo_estado CHECK (estado IN ('PENDIENTE', 'PARCIAL', 'PAGADO', 'ANULADO'))
);
CREATE INDEX ix_cargo_periodo ON cargo_suscripcion (periodo);
CREATE INDEX ix_cargo_estado ON cargo_suscripcion (estado);

CREATE TABLE prestamo (
    id_prestamo           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona            BIGINT NOT NULL,
    moneda                CHAR(3) NOT NULL,
    capital               NUMERIC(14,2) NOT NULL,
    tasa_mensual          NUMERIC(8,4) NOT NULL,
    plazo_meses           SMALLINT NOT NULL,
    fecha_prestamo        DATE NOT NULL,
    fecha_primer_pago     DATE NOT NULL,
    estricto_cumplimiento BOOLEAN NOT NULL,
    estado                VARCHAR(12) NOT NULL,
    motivo_estado         VARCHAR(250),
    fecha_estado          TIMESTAMP WITH TIME ZONE,
    notas                 TEXT,
    creado_en             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_prestamo_persona FOREIGN KEY (id_persona) REFERENCES persona (id_persona),
    CONSTRAINT fk_prestamo_moneda FOREIGN KEY (moneda) REFERENCES moneda (codigo),
    CONSTRAINT ck_prestamo_capital CHECK (capital > 0),
    CONSTRAINT ck_prestamo_tasa CHECK (tasa_mensual >= 0),
    CONSTRAINT ck_prestamo_plazo CHECK (plazo_meses > 0),
    CONSTRAINT ck_prestamo_estado CHECK (estado IN ('ACTIVO', 'CANCELADO', 'INCOBRABLE', 'ANULADO'))
);
CREATE INDEX ix_prestamo_persona ON prestamo (id_persona);
CREATE INDEX ix_prestamo_estado ON prestamo (estado);

CREATE TABLE cuota_prestamo (
    id_cuota            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_prestamo         BIGINT NOT NULL,
    numero_cuota        SMALLINT NOT NULL,
    fecha_vencimiento   DATE NOT NULL,
    capital_programado  NUMERIC(12,2) NOT NULL,
    interes_programado  NUMERIC(12,2) NOT NULL,
    monto_programado    NUMERIC(12,2) NOT NULL,
    monto_original      NUMERIC(12,2) NOT NULL,
    estado              VARCHAR(10) NOT NULL,
    CONSTRAINT fk_cuota_prestamo FOREIGN KEY (id_prestamo) REFERENCES prestamo (id_prestamo),
    CONSTRAINT uq_cuota_numero UNIQUE (id_prestamo, numero_cuota),
    CONSTRAINT ck_cuota_montos CHECK (capital_programado >= 0 AND interes_programado >= 0 AND monto_programado > 0),
    CONSTRAINT ck_cuota_suma CHECK (capital_programado + interes_programado = monto_programado),
    CONSTRAINT ck_cuota_estado CHECK (estado IN ('PENDIENTE', 'PARCIAL', 'PAGADA'))
);
CREATE INDEX ix_cuota_vencimiento ON cuota_prestamo (fecha_vencimiento);

CREATE TABLE cuota_ajuste (
    id_ajuste      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cuota       BIGINT NOT NULL,
    id_usuario     BIGINT,
    monto_anterior NUMERIC(12,2) NOT NULL,
    monto_nuevo    NUMERIC(12,2) NOT NULL,
    motivo         VARCHAR(250) NOT NULL,
    creado_en      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ajuste_cuota FOREIGN KEY (id_cuota) REFERENCES cuota_prestamo (id_cuota),
    CONSTRAINT fk_ajuste_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario),
    CONSTRAINT ck_ajuste_monto CHECK (monto_nuevo >= 0)
);

CREATE TABLE pago (
    id_pago           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona        BIGINT NOT NULL,
    moneda            CHAR(3) NOT NULL,
    fecha_pago        TIMESTAMP WITH TIME ZONE NOT NULL,
    monto             NUMERIC(12,2) NOT NULL,
    metodo_pago       VARCHAR(30) NOT NULL,
    referencia        VARCHAR(100),
    observacion       VARCHAR(250),
    estado            VARCHAR(10) NOT NULL,
    motivo_anulacion  VARCHAR(250),
    creado_en         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pago_persona FOREIGN KEY (id_persona) REFERENCES persona (id_persona),
    CONSTRAINT fk_pago_moneda FOREIGN KEY (moneda) REFERENCES moneda (codigo),
    CONSTRAINT ck_pago_monto CHECK (monto > 0),
    CONSTRAINT ck_pago_estado CHECK (estado IN ('REGISTRADO', 'ANULADO'))
);
CREATE INDEX ix_pago_persona ON pago (id_persona);
CREATE INDEX ix_pago_fecha ON pago (fecha_pago);
CREATE INDEX ix_pago_estado ON pago (estado);

CREATE TABLE aplicacion_pago (
    id_aplicacion  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pago        BIGINT NOT NULL,
    id_cargo       BIGINT,
    id_cuota       BIGINT,
    monto_aplicado NUMERIC(12,2) NOT NULL,
    monto_capital  NUMERIC(12,2),
    monto_interes  NUMERIC(12,2),
    CONSTRAINT fk_aplicacion_pago FOREIGN KEY (id_pago) REFERENCES pago (id_pago),
    CONSTRAINT fk_aplicacion_cargo FOREIGN KEY (id_cargo) REFERENCES cargo_suscripcion (id_cargo),
    CONSTRAINT fk_aplicacion_cuota FOREIGN KEY (id_cuota) REFERENCES cuota_prestamo (id_cuota),
    CONSTRAINT ck_aplicacion_monto CHECK (monto_aplicado > 0),
    CONSTRAINT ck_aplicacion_destino CHECK (
        (id_cargo IS NOT NULL AND id_cuota IS NULL AND monto_capital IS NULL AND monto_interes IS NULL)
        OR (id_cuota IS NOT NULL AND id_cargo IS NULL AND monto_capital >= 0 AND monto_interes >= 0
            AND monto_capital + monto_interes = monto_aplicado)
    )
);
CREATE INDEX ix_aplicacion_pago ON aplicacion_pago (id_pago);
CREATE INDEX ix_aplicacion_cargo ON aplicacion_pago (id_cargo);
CREATE INDEX ix_aplicacion_cuota ON aplicacion_pago (id_cuota);

CREATE TABLE comprobante_pago (
    id_comprobante BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pago        BIGINT NOT NULL,
    imagen_base64  TEXT NOT NULL,
    mime_type      VARCHAR(20) NOT NULL DEFAULT 'image/png',
    ancho          SMALLINT NOT NULL,
    alto           SMALLINT NOT NULL,
    sha256         CHAR(64) NOT NULL,
    subido_en      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_comprobante_pago FOREIGN KEY (id_pago) REFERENCES pago (id_pago),
    CONSTRAINT ck_comprobante_dimensiones CHECK (ancho > 0 AND alto > 0)
);
CREATE INDEX ix_comprobante_pago ON comprobante_pago (id_pago);
CREATE INDEX ix_comprobante_sha ON comprobante_pago (sha256);

CREATE TABLE auditoria (
    id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario   BIGINT,
    entidad      VARCHAR(60) NOT NULL,
    id_entidad   BIGINT,
    accion       VARCHAR(40) NOT NULL,
    antes        TEXT,
    despues      TEXT,
    creado_en    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_auditoria_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
);
CREATE INDEX ix_auditoria_entidad ON auditoria (entidad, id_entidad);
CREATE INDEX ix_auditoria_fecha ON auditoria (creado_en);

CREATE TABLE configuracion (
    clave VARCHAR(60) PRIMARY KEY,
    valor VARCHAR(250) NOT NULL
);
